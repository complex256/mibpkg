#!/usr/bin/env bash
# Regenerate packaging/ca.pem: the roots mibpkg trusts for online sources (GitHub, Let's Encrypt,
# Google Trust Services / Cloudflare, Amazon), taken from the macOS system root store.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
python3 - "$ROOT/packaging/ca.pem" <<'EOF'
import re, subprocess, sys
want = ["ISRG Root X1", "DigiCert Global Root G2", "DigiCert Global Root CA",
        "DigiCert High Assurance EV Root CA", "USERTrust RSA Certification Authority",
        "USERTrust ECC Certification Authority", "GTS Root R1", "GTS Root R2", "GTS Root R3",
        "GTS Root R4", "Amazon Root CA 1"]
pems = re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", open("/etc/ssl/cert.pem").read(), re.S)
found = {}
for p in pems:
    subj = subprocess.run(["openssl", "x509", "-noout", "-subject", "-nameopt", "multiline"], input=p, capture_output=True, text=True).stdout
    m = re.search(r"commonName\s*=\s*(.+)", subj)
    if m and m.group(1).strip() in want and m.group(1).strip() not in found:
        found[m.group(1).strip()] = p
missing = [w for w in want if w not in found]
if missing:
    sys.exit(f"missing roots: {missing}")
with open(sys.argv[1], "w") as f:
    f.write("# mibpkg CA bundle - generated by scripts/make-ca.sh; do not edit\n")
    for w in want:
        f.write(f"# {w}\n{found[w]}\n")
EOF
echo "wrote $ROOT/packaging/ca.pem"
